"""Write docs/evaluation-report.md from a real run of the acceptance criteria.

    python backend/scripts/write_evaluation_report.py

The report is a deliverable in its own right, so it is generated from a
measurement rather than written by hand. Everything in it, including anything
that falls short, comes straight out of the run.
"""

from __future__ import annotations

import datetime as dt
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent
if str(BACKEND) not in sys.path:
    sys.path.insert(0, str(BACKEND))

from app.config import settings  # noqa: E402
from app.db import create_all, session_scope  # noqa: E402
from app.evaluation.runner import run_evaluation  # noqa: E402
from app.models import Product  # noqa: E402

OUTPUT = BACKEND.parent / "docs" / "evaluation-report.md"

VERDICT = {True: "**pass**", False: "**below the bar**", None: "not measured"}


def main() -> int:
    create_all()
    with session_scope() as session:
        from sqlalchemy import func, select

        catalogue = int(session.scalar(select(func.count()).select_from(Product)) or 0)
        if catalogue == 0:
            print("Load the demonstration data first.")
            return 1

        report = run_evaluation(
            session, request_count=200, lines_per_request=25, revision_pairs=30
        )

    lines: list[str] = [
        "# QuoteAgent: evaluation report",
        "",
        "Written for: the product owner, and anybody who has to defend these",
        "numbers to a buyer's engineer.",
        "",
        "Generated by `python backend/scripts/write_evaluation_report.py`. Every",
        "figure below comes out of the run named in the header; nothing is",
        "rounded in the product's favour and nothing that fell short has been",
        "left out.",
        "",
        "---",
        "",
        "## The run",
        "",
        f"| | |",
        f"|---|---|",
        f"| Date | {dt.datetime.now().strftime('%d %B %Y, %H:%M')} |",
        f"| Reasoning engine | {report['engine']} |",
        f"| Catalogue | {catalogue:,} parts |",
        f"| Test set | {report['requests']} requests, {report['sample_size']:,} lines |",
        f"| Took | {report['seconds']} seconds |",
        f"| Overall | {'all measured criteria met' if report['passed'] else 'at least one criterion not met'} |",
        "",
        "## Results",
        "",
        "| Measure | Pass bar | Measured | Verdict |",
        "|---|---|---|---|",
    ]

    for criterion in report["criteria"]:
        lines.append(
            f"| {criterion['name']} | {criterion['pass_bar']} | "
            f"{criterion['measured']} | {VERDICT[criterion['passed']]} |"
        )

    lines += ["", "## How each one was measured", ""]
    for criterion in report["criteria"]:
        lines += [
            f"### {criterion['name']}",
            "",
            f"- **Bar:** {criterion['pass_bar']}",
            f"- **Measured:** {criterion['measured']}",
            f"- **Sample:** {criterion['sample']}",
        ]
        detail = criterion.get("detail") or {}
        for key in ("how", "why", "note"):
            if detail.get(key):
                lines.append(f"- **Note:** {detail[key]}")
        if criterion["key"] == "line_matching":
            lines.append(
                f"- Correct {detail.get('correct', 0):,} of {detail.get('total', 0):,}; "
                f"{detail.get('wrongly_flagged', 0)} clear line(s) were flagged instead of matched."
            )
        if criterion["key"] == "ambiguity_handling":
            lines.append(
                f"- Flagged {detail.get('unclear_flagged', 0):,} of "
                f"{detail.get('unclear_total', 0):,} genuinely unclear lines; "
                f"{detail.get('clear_wrongly_flagged', 0)} of {detail.get('clear_total', 0):,} "
                "clear lines were flagged when they should not have been."
            )
        if criterion["key"] == "revisions":
            lines.append(
                f"- {detail.get('changes_detected', 0)} of "
                f"{detail.get('changes_expected', 0)} changes detected."
            )
        if criterion["key"] == "speed":
            lines.append(
                f"- Median {detail.get('median_seconds', 0)} s, slowest "
                f"{detail.get('slowest_seconds', 0)} s, scaled to forty lines."
            )
        lines.append("")

    mistakes = report.get("mistakes") or []
    lines += ["## Every line it got wrong", ""]
    if not mistakes:
        lines += ["The run produced no incorrect matches and no wrongly flagged lines.", ""]
    else:
        lines += [
            f"{len(mistakes)} line(s), listed rather than summarised away.",
            "",
            "| What went wrong | The line | Expected | Got |",
            "|---|---|---|---|",
        ]
        for mistake in mistakes[:40]:
            text = str(mistake.get("text", "")).replace("|", "\\|")
            lines.append(
                f"| {mistake.get('kind', '')} | `{text}` | "
                f"{mistake.get('expected', mistake.get('why_unclear', ''))} | "
                f"{mistake.get('got', mistake.get('matched_to', mistake.get('reason', '')))} |"
            )
        lines.append("")

    lines += [
        "## What this report does not tell you",
        "",
        "- **Edits by the salesperson** cannot be measured without salespeople",
        "  editing real drafts. The product records the draft and the sent",
        "  version of every quote, so the figure becomes available in the first",
        "  week of a pilot. It is reported as not measured rather than estimated.",
        "- **Speed** is the agent's own working time. It excludes waiting for a",
        "  customer or a supplier, which is the part that actually takes days,",
        f"  and with the {report['engine']} engine it excludes network time.",
        "- **The test set is generated** from the same catalogue the product",
        "  searches. It exercises the matching rules hard, including lines built",
        "  with an attribute deliberately removed or contradicted, but it is not",
        "  a sample of one customer's real traffic. Replacing it with real",
        "  anonymised requests is the first thing discovery should do.",
        "",
    ]

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUTPUT}")
    print(f"Overall: {'pass' if report['passed'] else 'NOT MET'}")
    for criterion in report["criteria"]:
        mark = {True: "pass", False: "FAIL", None: "not measured"}[criterion["passed"]]
        print(f"  {criterion['name']:<28} {mark:<13} {criterion['measured']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
